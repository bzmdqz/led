"""Convert a 128x128 PNG into src/logo.c with one bit per RGB channel."""

import argparse
from pathlib import Path

from PIL import Image


SIZE = 128


def rgb_bits(pixel: tuple[int, int, int, int]) -> int:
    red, green, blue, alpha = pixel
    if alpha < 128:
        return 0
    return (red >= 128) | ((green >= 128) << 1) | ((blue >= 128) << 2)


def encode_row(image: Image.Image, y: int) -> bytes:
    packed = bytearray()
    for x in range(0, SIZE, 2):
        left = rgb_bits(image.getpixel((x, y)))
        right = rgb_bits(image.getpixel((x + 1, y)))
        packed.append((left << 4) | right)
    return bytes(packed)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path, help="128x128 PNG")
    parser.add_argument("output", type=Path, nargs="?", default=Path("src/logo.c"))
    args = parser.parse_args()

    with Image.open(args.image) as source:
        if source.size != (SIZE, SIZE):
            parser.error(f"image must be {SIZE}x{SIZE}, got {source.width}x{source.height}")
        image = source.convert("RGBA")

    lines = []
    for y in range(SIZE):
        packed = encode_row(image, y)
        lines.append("        {")
        for start in range(0, len(packed), 16):
            group = packed[start:start + 16]
            lines.append("            " + ", ".join(f"0x{value:02x}" for value in group) + ",")
        lines.append("        },")

    args.output.write_text(
        '// Generated by tools/image_to_logo.py.\n'
        '#include "logo.h"\n\n'
        'const Hub75Image logo = {\n'
        '    .row = {\n'
        + "\n".join(lines)
        + "\n    }\n};\n",
        encoding="ascii",
    )


if __name__ == "__main__":
    main()
